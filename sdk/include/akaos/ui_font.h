#ifndef AKAOS_UI_FONT_H
#define AKAOS_UI_FONT_H

#include <stdint.h>

/* Small, dependency-free 5x7 UI font for native desktop surfaces.  The
 * framebuffer TTY keeps its full VGA/CP437 font; this compact atlas is only
 * for panel labels and window chrome so every userspace GUI can share the
 * same crisp 1:1 glyphs without linking a font library. */
#define AKAOS_UI_FONT_WIDTH 5U
#define AKAOS_UI_FONT_HEIGHT 7U

static inline uint8_t akaos_ui_font_row(char character, uint32_t row) {
    static const uint8_t letters[26][7] = {
        {0x0e, 0x11, 0x11, 0x1f, 0x11, 0x11, 0x11}, /* A */
        {0x1e, 0x11, 0x11, 0x1e, 0x11, 0x11, 0x1e}, /* B */
        {0x0f, 0x10, 0x10, 0x10, 0x10, 0x10, 0x0f}, /* C */
        {0x1e, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1e}, /* D */
        {0x1f, 0x10, 0x10, 0x1e, 0x10, 0x10, 0x1f}, /* E */
        {0x1f, 0x10, 0x10, 0x1e, 0x10, 0x10, 0x10}, /* F */
        {0x0f, 0x10, 0x10, 0x17, 0x11, 0x11, 0x0f}, /* G */
        {0x11, 0x11, 0x11, 0x1f, 0x11, 0x11, 0x11}, /* H */
        {0x1f, 0x04, 0x04, 0x04, 0x04, 0x04, 0x1f}, /* I */
        {0x01, 0x01, 0x01, 0x01, 0x11, 0x11, 0x0e}, /* J */
        {0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11}, /* K */
        {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1f}, /* L */
        {0x11, 0x1b, 0x15, 0x15, 0x11, 0x11, 0x11}, /* M */
        {0x11, 0x19, 0x19, 0x15, 0x13, 0x13, 0x11}, /* N */
        {0x0e, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0e}, /* O */
        {0x1e, 0x11, 0x11, 0x1e, 0x10, 0x10, 0x10}, /* P */
        {0x0e, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0d}, /* Q */
        {0x1e, 0x11, 0x11, 0x1e, 0x14, 0x12, 0x11}, /* R */
        {0x0f, 0x10, 0x10, 0x0e, 0x01, 0x01, 0x1e}, /* S */
        {0x1f, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04}, /* T */
        {0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0e}, /* U */
        {0x11, 0x11, 0x11, 0x11, 0x11, 0x0a, 0x04}, /* V */
        {0x11, 0x11, 0x11, 0x15, 0x15, 0x1b, 0x11}, /* W */
        {0x11, 0x11, 0x0a, 0x04, 0x0a, 0x11, 0x11}, /* X */
        {0x11, 0x11, 0x0a, 0x04, 0x04, 0x04, 0x04}, /* Y */
        {0x1f, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1f}, /* Z */
    };
    static const uint8_t digits[10][7] = {
        {0x0e, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0e}, /* 0 */
        {0x04, 0x0c, 0x04, 0x04, 0x04, 0x04, 0x0e}, /* 1 */
        {0x0e, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1f}, /* 2 */
        {0x1e, 0x01, 0x01, 0x0e, 0x01, 0x01, 0x1e}, /* 3 */
        {0x02, 0x06, 0x0a, 0x12, 0x1f, 0x02, 0x02}, /* 4 */
        {0x1f, 0x10, 0x10, 0x1e, 0x01, 0x01, 0x1e}, /* 5 */
        {0x06, 0x08, 0x10, 0x1e, 0x11, 0x11, 0x0e}, /* 6 */
        {0x1f, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08}, /* 7 */
        {0x0e, 0x11, 0x11, 0x0e, 0x11, 0x11, 0x0e}, /* 8 */
        {0x0e, 0x11, 0x11, 0x0f, 0x01, 0x02, 0x0c}, /* 9 */
    };

    if (row >= AKAOS_UI_FONT_HEIGHT) return 0;
    if (character >= 'a' && character <= 'z') character = (char)(character - 'a' + 'A');
    if (character >= 'A' && character <= 'Z') return letters[(unsigned)(character - 'A')][row];
    if (character >= '0' && character <= '9') return digits[(unsigned)(character - '0')][row];
    switch (character) {
        case ' ': return 0;
        case '.': return row == 6 ? 0x04 : 0;
        case ':': return (row == 2 || row == 5) ? 0x04 : 0;
        case '-': return row == 3 ? 0x1f : 0;
        case '_': return row == 6 ? 0x1f : 0;
        case '/': return (row == 0 ? 0x10 : row == 1 ? 0x08 : row == 2 ? 0x08 : row == 3 ? 0x04 : row == 4 ? 0x02 : row == 5 ? 0x02 : 0x01);
        case '+': return (row == 3 ? 0x1f : (row == 2 || row == 4) ? 0x04 : 0);
        case '#': return (row == 1 || row == 5) ? 0x0a : (row == 2 || row == 3 || row == 4) ? 0x1f : 0;
        case '@': return (row == 1 || row == 5) ? 0x0e : (row == 2 || row == 3 || row == 4) ? 0x11 : 0;
        default: return 0;
    }
}

#endif
