def parse_upstream(path):
    """Re-derive the 4096 font bytes from a linux font_8x16.c source file."""
    src = path.read_text(encoding="latin-1")
    marker = re.compile(r"=\s*\{\s*\{\s*0,\s*0,\s*FONTDATAMAX,\s*0\s*\},\s*\{")
    match = marker.search(src)
    if not match:
        raise SystemExit("could not locate fontdata_8x16 data block in source")
    block = src[match.end():src.find("};\n", match.end())]
    data = bytes(int(token, 16) for token in re.findall(r"0x[0-9a-fA-F]{1,2}(?=,)", block))
    if len(data) != FONTDATAMAX:
        raise SystemExit("upstream font has %d bytes, expected %d" % (len(data), FONTDATAMAX))
    return data


def main():
    if len(sys.argv) not in (2, 3):
        print("usage: generate_vga_font.py OUTPUT_HEADER [SOURCE_C]", file=sys.stderr)
        return 2
    output_path = Path(sys.argv[1])
    data = FONT_BYTES
    if len(sys.argv) == 3:
        upstream = parse_upstream(Path(sys.argv[2]))
        if upstream != FONT_BYTES:
            raise SystemExit("upstream font data does not match embedded blob")
        data = upstream
    if len(data) != FONTDATAMAX:
        raise SystemExit("font data size mismatch")

    rows = []
    for offset in range(0, len(data), CELL_HEIGHT):
        rows.append("    " + ", ".join("0x%02x" % b for b in data[offset:offset + CELL_HEIGHT]))
    body = ",\n".join(rows)

    header = (
        "#ifndef AKAOS_GENERATED_VGA8X16_FONT_H\n"
        "#define AKAOS_GENERATED_VGA8X16_FONT_H\n\n"
        "#include <stdint.h>\n\n"
        "/* 8x16 VGA/CP437 bitmap font (public-domain IBM VGA ROM data). */\n"
        "#define AKAOS_VGA_FONT_FIRST 0\n"
        "#define AKAOS_VGA_FONT_LAST 255\n"
        "#define AKAOS_VGA_FONT_GLYPHS 256\n"
        "#define AKAOS_VGA_FONT_CELL_WIDTH %d\n"
        "#define AKAOS_VGA_FONT_CELL_HEIGHT %d\n\n"
        "static const uint8_t akaos_vga_font[%d] = {\n"
        "%s\n"
        "};\n\n"
        "#endif\n"
    ) % (CELL_WIDTH, CELL_HEIGHT, GLYPHS * CELL_HEIGHT, body)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(header, encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
