static uint32_t crc_table[256];

void init_crc(void) {
    memcpy(crc_table, crctab, sizeof(crc_table));
}

uint32_t calculate_crc(FILE *f, uint64_t *size) {
    uint32_t crc = 0;
    *size = 0;
    int c;
    while ((c = fgetc(f)) != EOF) {
        crc = (crc << 8) ^ crc_table[((crc >> 24) ^ c) & 0xff];
        (*size)++;
    }
    return crc;
}

int main(int argc, char **argv) {
    init_crc();
    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--help") == 0) {
            printf("Usage: cksum [File]...\n");
            return 0;
        }
        if (strcmp(argv[i], "--version") == 0) {
            printf("cksum (akaOS) 0.1\n");
            return 0;
        }
    }

    if (argc == 1) {
        uint64_t size;
        uint32_t crc = calculate_crc(stdin, &size);
        printf("%u %llu\n", crc, (unsigned long long)size);
    } else {
        for (int i = 1; i < argc; i++) {
            FILE *f = fopen(argv[i], "rb");
            if (!f) {
                perror(argv[i]);
                continue;
            }
            uint64_t size;
            uint32_t crc = calculate_crc(f, &size);
            printf("%u %llu %s\n", crc, (unsigned long long)size, argv[i]);
            fclose(f);
        }
    }
    return 0;
}
