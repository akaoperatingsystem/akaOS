/* BSD and historical POSIX programs include <sys/fcntl.h> for the file
 * control interfaces whose standard header is <fcntl.h>.  akaOS keeps the
 * single standard header and forwards this spelling to it, so ported software
 * compiles without a source change. */
#ifndef AKAOS_SYS_FCNTL_H
#define AKAOS_SYS_FCNTL_H

#include <fcntl.h>

#endif /* AKAOS_SYS_FCNTL_H */
